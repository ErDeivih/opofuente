"""El catálogo de materias de I.3 (el Gobierno: composición, nombramiento y cese; sus funciones; y
sus relaciones con las Cortes Generales).

I.3 es un tema **normativo** y su índice es la estructura de la norma, como en I.1, I.5 e I.7: los
artículos 97 a 116 de la Constitución —el Título IV entero, «Del Gobierno y de la Administración», y
el Título V, «De las relaciones entre el Gobierno y las Cortes Generales»— más la Ley 50/1997, de 27
de noviembre, del Gobierno, que es la que desarrolla la composición, el funcionamiento y el
procedimiento de elaboración de las normas. Sus tres epígrafes oficiales son el esqueleto —la
composición, el nombramiento y el cese (17 grupos), las funciones del Gobierno (8) y las relaciones
con las Cortes Generales (27)— y **116 de sus 168 grupos no traen epígrafe**, así que el enunciado
tiene que decidir por su cuenta en la mayoría del banco.

Catorce apartados:

- **la composición del Gobierno y sus miembros** (I.3.1): de quién se compone, quién es el Jefe del
  Gobierno, el Presidente y sus competencias propias, los Vicepresidentes y quién los cesa, los
  Ministros y quién los propone y los nombra, y los Secretarios de Estado;
- **los órganos de apoyo del Gobierno** (I.3.1): el Consejo de Ministros y quién lo preside,
  convoca y actúa como secretario, las Comisiones Delegadas, la Comisión General de Secretarios de
  Estado y Subsecretarios y el Secretariado del Gobierno con sus funciones; y quién expide los
  Decretos acordados en el Consejo de Ministros;
- **el nombramiento, la investidura y el cese** (I.3.1): la propuesta del Rey previa consulta, la
  votación de investidura y la mayoría que hace falta en primera y en segunda vuelta, el plazo de
  dos meses para la disolución de las Cámaras, el cese del Gobierno y sus motivos, el Gobierno
  cesante y el Gobierno en funciones con lo que no puede hacer;
- **el Consejo de Estado y la responsabilidad del Gobierno** (I.3.1): qué es el Consejo de Estado,
  la responsabilidad política y la responsabilidad criminal del Presidente y de los demás miembros
  del Gobierno y ante quién es exigible;
- **el Rey y el refrendo de los actos del Gobierno** (I.3.1 y I.3.3), que tiene su propio apartado
  porque el artículo 64 está en el Título IV: qué actos del Rey refrenda el Presidente, quién
  responde de los actos del Rey, el Rey presidiendo el Consejo de Ministros y su relación con las
  Cortes Generales;
- **las funciones del Gobierno** (I.3.2): el artículo 97 y lo que el Gobierno dirige —la política
  interior y exterior, la Administración civil y militar y la defensa del Estado—, las funciones
  ejecutiva y de dirección, y las Fuerzas y Cuerpos de seguridad bajo su dependencia;
- **la potestad reglamentaria y la elaboración de las normas** (I.3.2): el procedimiento de
  elaboración de los reglamentos, la tramitación urgente de los anteproyectos, los reales decretos
  legislativos y los reales decretos, las leyes de delegación y las leyes de bases con lo que no
  pueden hacer, y la iniciativa legislativa del Gobierno;
- **la moción de censura** (I.3.3): cómo se propone y por cuántos Diputados como mínimo, el
  candidato que tiene que incluir, los cinco días entre la presentación y la votación, cuándo no
  puede votarse, qué pasa si no se aprueba y la moción de censura alternativa;
- **la cuestión de confianza** (I.3.3): quién la plantea y ante quién, la deliberación previa del
  Consejo de Ministros, cuándo se entiende otorgada y qué pasa si el Congreso niega su confianza;
- **las interpelaciones y las preguntas al Gobierno** (I.3.3): el artículo 111, las interpelaciones
  y las preguntas que se formulan desde las Cámaras, la moción en la que la Cámara manifiesta su
  posición y la comparecencia del Gobierno;
- **la responsabilidad política y el control parlamentario** (I.3.3): la responsabilidad solidaria
  ante el Congreso de los Diputados, la gestión política del Gobierno, el control de las Cámaras y
  la aprobación de los Presupuestos Generales del Estado;
- y **los estados de alarma, de excepción y de sitio** (I.3.3), que también tienen su apartado
  porque el artículo 116 cierra el Título V: quién declara cada uno, su plazo máximo, su prórroga y
  sus efectos sobre los derechos.

Tres decisiones de los patrones y de los cajones, dichas donde se leen:

- **este banco trae muchísimos enunciados sin sujeto.** «Señale la afirmación verdadera», «Señale la
  correcta», «Indique cuál de las siguientes…» no dicen de qué materia hablan, y son decenas. Cuando
  el grupo **sí trae epígrafe**, ese epígrafe ya dice de qué parte del tema es, y su sitio es el
  **cajón del epígrafe** (`i-3-1-otros`, `i-3-2-otros`, `i-3-3-otros`), que es un apartado real
  —«otras cuestiones del Gobierno y de su relación con las Cortes»— y no un escondite. Es la misma
  decisión que tomaron los catálogos de I.2 y de I.4, que también tienen sus cajones. Los que **no**
  traen epígrafe y tampoco sujeto no se colocan en ninguna parte: van a la bandeja del propietario,
  porque no hay de qué decidirlo;
- **la moción de censura y la cuestión de confianza no comparten apartado** aunque las dos acaben en
  la misma votación: son dos instituciones distintas —una la propone el Congreso y la otra el
  Presidente— y el banco las pregunta por separado, con sus plazos y sus mayorías;
- y **lo que es de otro tema no se lava**, y este banco arrastra bastante: el estándar
  **ANSI/TIA-942-B** de la zona de un CPD y el TIER de un CPD son de **IV.5.7**, el **CSV** del RFC
  4180 es de **II.3**, el **TREBEP** y los funcionarios interinos son de **I.4**, el **Consejo de
  Transparencia y Buen Gobierno** y la Ley 19/2013 son de **I.4**, la **Ley 3/2007** de función
  pública de las Illes Balears es de otro bloque, **Jakarta EE** y **Docker** son de **III.5** y
  **IV.3**, y los **titulares reales** del blanqueo de capitales no son del Gobierno. Todo eso va a
  la bandeja del propietario con su motivo (`Motivo.SIN_MATERIA_EN_EL_INDICE`) en vez de a un
  apartado inventado.
"""

